import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { repositoryPath } from "./paths.mjs";
import { parseDocument } from "./parse.mjs";
import { markdownFiles } from "./audit.mjs";
import { resolveInternalLink } from "./resolve.mjs";
const escape = (text) => text.replace(/([\\\[\]])/g, "\\$1");
const encode = (path) => path.split("/").map(encodeURIComponent).join("/");
const link = (from, to) =>
  encode(relative(dirname(from), to).replaceAll("\\", "/"));
export function generate(root, { check = false } = {}) {
  const diagnostics = [],
    edits = new Map(),
    docs = new Map();
  const fail = (code, path, target) => diagnostics.push({ code, path, target });
  for (const path of [
    "README.md",
    "Draft/README.md",
    "Draft/_sidebar.md",
    "Draft/Subject_Index.md",
    "Draft/search-paths.js",
  ]) {
    try {
      repositoryPath(root, path, { allowMissing: true });
    } catch (error) {
      fail("unsafe-output-path", path, error.message);
    }
  }
  if (diagnostics.length) return { changedPaths: [], diagnostics };
  let manifest;
  try {
    manifest = JSON.parse(
      readFileSync(repositoryPath(root, "navigation/topics.json"), "utf8"),
    );
  } catch (error) {
    return {
      changedPaths: [],
      diagnostics: [{ code: "invalid-manifest", target: error.message }],
    };
  }
  if (
    manifest.version !== 1 ||
    !Array.isArray(manifest.pages) ||
    !Array.isArray(manifest.tocPages)
  )
    return { changedPaths: [], diagnostics: [{ code: "invalid-manifest" }] };
  const seen = new Set();
  for (const page of manifest.pages) {
    if (
      typeof page.path !== "string" ||
      typeof page.title !== "string" ||
      typeof page.category !== "string"
    ) {
      fail("invalid-page", "navigation/topics.json", page.path);
      continue;
    }
    if (seen.has(page.path))
      fail("duplicate-page", "navigation/topics.json", page.path);
    seen.add(page.path);
    const resolution = resolveInternalLink(root, "README.md", page.path, docs);
    if (resolution.kind !== "internal" || !page.path.endsWith(".md"))
      fail("invalid-page", "navigation/topics.json", page.path);
    for (const subject of page.subjects ?? []) {
      if (
        typeof subject.label !== "string" ||
        !subject.fragment ||
        resolveInternalLink(
          root,
          "README.md",
          page.path + "#" + encodeURIComponent(subject.fragment),
          docs,
        ).kind !== "internal"
      )
        fail("invalid-subject", page.path, subject.fragment);
    }
  }
  const read = (path) => readFileSync(repositoryPath(root, path), "utf8");
  const block = (path, name, body) => {
    let source;
    try {
      source = edits.get(path) ?? read(path);
    } catch {
      fail("missing-managed-file", path, name);
      return;
    }
    const start = `<!-- nav:${name}:start -->`,
      end = `<!-- nav:${name}:end -->`;
    if (
      source.split(start).length !== 2 ||
      source.split(end).length !== 2 ||
      source.indexOf(start) > source.indexOf(end)
    ) {
      fail("invalid-markers", path, name);
      return;
    }
    const newline = source.includes("\r\n") ? "\r\n" : "\n";
    edits.set(
      path,
      source.slice(0, source.indexOf(start) + start.length) +
        newline +
        body.replaceAll("\n", newline) +
        newline +
        source.slice(source.indexOf(end)),
    );
  };
  const topicList = (from) => {
    const lines = [];
    let category;
    for (const page of manifest.pages) {
      if (page.category !== category) {
        category = page.category;
        lines.push(`### ${escape(category)}`, "");
      }
      lines.push(`- [${escape(page.title)}](${link(from, page.path)})`);
    }
    lines.push(
      "",
      "- [Alphabetical subject index](" +
        link(from, "Draft/Subject_Index.md") +
        ")",
    );
    return lines.join("\n");
  };
  if (diagnostics.length) return { changedPaths: [], diagnostics };
  block("README.md", "topics", topicList("README.md"));
  block("Draft/README.md", "topics", topicList("Draft/README.md"));
  edits.set(
    "Draft/_sidebar.md",
    "<!-- Generated by npm run nav:generate; edit navigation/topics.json. -->\n\n- [Home](README.md)\n- [Alphabetical subject index](Subject_Index.md)\n\n" +
      topicList("Draft/_sidebar.md").replace(/^### (.+)$/gm, "- **$1**") +
      "\n",
  );
  const searchPaths = [
    ...new Set([...markdownFiles(root), "Draft/Subject_Index.md"]),
  ]
    .sort()
    .filter(
      (p) =>
        p.startsWith("Draft/") &&
        !["Draft/_sidebar.md", "Draft/index.md"].includes(p),
    )
    .map((p) => "/" + encode(p.slice(6).replace(/\.md$/, "")));
  edits.set(
    "Draft/search-paths.js",
    "// Generated by npm run nav:generate.\nwindow.$docsify.search.paths = " +
      JSON.stringify(searchPaths, null, 2) +
      ";\n",
  );
  const subjects = [];
  for (const page of manifest.pages) {
    for (const label of [page.title, ...(page.aliases ?? [])])
      subjects.push({ label, path: page.path, fragment: "" });
    for (const subject of page.subjects ?? [])
      for (const label of [subject.label, ...(subject.aliases ?? [])])
        subjects.push({ label, path: page.path, fragment: subject.fragment });
  }
  subjects.sort(
    (a, b) =>
      a.label.localeCompare(b.label, "en", { sensitivity: "base" }) ||
      a.label.localeCompare(b.label, "en") ||
      a.path.localeCompare(b.path, "en") ||
      a.fragment.localeCompare(b.fragment, "en"),
  );
  edits.set(
    "Draft/Subject_Index.md",
    "# Alphabetical Subject Index\n\n<!-- Generated by npm run nav:generate; edit navigation/topics.json. -->\n\nCoverage: all main topics, with selected subjects from migrated pages. This is not an index of every resource.\n\n" +
      subjects
        .map(
          (s) =>
            `- [${escape(s.label)}](${link("Draft/Subject_Index.md", s.path)}${s.fragment ? "#" + encodeURIComponent(s.fragment) : ""})`,
        )
        .join("\n") +
      "\n",
  );
  for (const path of manifest.tocPages) {
    const page = manifest.pages.find((p) => p.path === path);
    if (!page) {
      fail("unlisted-toc-page", path, "");
      continue;
    }
    const source = read(path),
      doc = docs.get(path) ?? parseDocument(source, path);
    const headings = doc.headings.filter(
      (h) =>
        h.depth > 1 &&
        h.depth <= (page.tocDepth ?? 3) &&
        h.text !== "Table of Contents",
    );
    const body = headings
      .map((h) => {
        const explicit = doc.anchors.find(
          (a) => a.explicit && a.line === h.line,
        )?.fragment;
        return (
          "  ".repeat(h.depth - 2) +
          `- [${escape(h.text)}](#${encodeURIComponent(explicit ?? h.fragment)})`
        );
      })
      .join("\n");
    block(path, "toc", body);
  }
  for (const path of edits.keys()) {
    try {
      repositoryPath(root, path, { allowMissing: true });
    } catch (error) {
      fail("unsafe-output-path", path, error.message);
    }
  }
  if (diagnostics.length) return { changedPaths: [], diagnostics };
  const changedPaths = [...edits]
    .filter(
      ([path, text]) => !existsSync(join(root, path)) || read(path) !== text,
    )
    .map(([path]) => path);
  if (!check && !diagnostics.length)
    for (const path of changedPaths)
      writeFileSync(
        repositoryPath(root, path, { allowMissing: true }),
        edits.get(path),
      );
  return { changedPaths, diagnostics };
}
